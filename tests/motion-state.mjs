import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
const read = p => readFileSync(new URL('../' + p, import.meta.url), 'utf8')
const motion = read('lib/core/Motion.luau')
const source = read('lib/RiftUI.luau')
const subtabs = read('lib/core/SubTabs.luau')
const orb = read('lib/core/ToolbarOrb.luau')
const panelResize = read('lib/core/PanelResize.luau')
const published = read('public/RiftUI.luau')
const ci = read('.github/workflows/verify-subtabs-lune.yml')
assert.match(motion, /local motionByOwner = setmetatable\(\{\}, \{ __mode = "k" \}\)/)
for(const fn of ['play','transition','cancel','cancelAll','getState']){
  assert.ok(motion.includes('function Motion.'+fn+'('), 'missing Motion.'+fn)
}
for(const preset of ['Micro','Control','Panel','Ripple','Dismiss']){
  assert.match(motion,new RegExp(preset+' = TweenInfo'))
}
assert.match(motion, /Motion.cancel\(owner, id\)/)
assert.match(motion, /entry.Cancelled = true/)
assert.match(motion, /for _, conn in entry.Connections do conn:Disconnect\(\) end/)
assert.match(motion, /if onComplete and not owner._destroyed then onComplete\(state\) end/)
assert.match(motion, /RiftUI.Motion = Motion/)
assert.match(source, /Motion.transition\(self, "panel-visibility", "open"/)
assert.match(source, /Motion.transition\(self, "panel-visibility", "closed"/)
assert.match(source, /Motion.play\(self, "popup-position"/)
assert.match(source, /Motion.cancel\(self, "popup-position"\)/)
assert.match(source, /Motion.play\(hub, key, clip/)
assert.match(source, /Motion.cancelAll\(self\)/)
assert.match(subtabs, /Motion.transition\(self, "subtab-rail", "open"/)
assert.match(subtabs, /Motion.transition\(self, "subtab-rail", "closed"/)
assert.match(subtabs, /local resuming = self._subTabRail.Visible/)
assert.match(orb, /Motion.transition\(self, "toolbar-orb-glyph"/)
assert.ok(published.includes(motion.trim()), 'built Motion stale')
assert.ok(published.includes(subtabs.trim()), 'built SubTabs stale')
assert.ok(published.includes(orb.trim()), 'built Orb stale')
assert.ok(published.includes(panelResize.trim()), 'built resize runtime stale')
assert.match(source, /--@@PANEL_RESIZE@@/, 'resize module marker missing')
assert.match(panelResize, /bindPointerDrag\(self, grip/, 'resize must share pointer capture')
assert.match(panelResize, /self:_savePref\\("PanelSizes", table\\.clone\\(self\\._panelSizes\\)\\)/, 'resized pages must persist independently')
assert.match(panelResize, /function Hub:_panelSizeKey\\(tab\\)/)
assert.match(panelResize, /function Hub:_panelSizeFor\\(tab\\)/)
assert.match(panelResize, /startPage ~= self:_contentTab\\(self\\._open\\)/, 'gesture must not bleed into next page')
assert.doesNotMatch(panelResize, /Name = "GripLine"/, 'hidden resize hit target must not draw grooves')
assert.match(panelResize, /Name = "PanelResizeGrip", BackgroundTransparency = 1, TextTransparency = 1/, 'hit target remains invisible')
assert.match(source, /_panelSizes = type\\(saved and saved\\.PanelSizes\\)/, 'load saved per-page dimensions')
assert.match(source, /self:_panelSizeFor\\(tab\\)/, 'page size must be resolved for active page')
assert.match(source, /local narrow = panelWidth < 550/, 'narrow panel must reflow')
assert.ok(ci.includes('lune run tests/motion-state-lune'),'CI must run interruption tests')
assert.match(source, /local settings = tab == self\.SettingsTab/, 'settings must have responsive width')
assert.match(source, /local panelWidth = math\.min\(settings and 680 or 620/, 'wider panel must adapt to viewport')
assert.match(source, /self\.Panel = create\("Frame"/, 'the main text panel must avoid CanvasGroup texture rasterization')
assert.match(source, /Name = "RowsClip",[\s\S]*?Visible = not section\._collapsed/, 'section text clipping must use native Frame visibility')
assert.match(source, /clip\.Visible = not shut/, 'section folding must conceal clipped controls without group opacity')
assert.doesNotMatch(source, /Motion\.play\(hub, key \.\. ":fade", clip/, 'section text must not be downsampled through opacity layers')
assert.match(source, /content\._lastMeasuredHeight = measuredHeight/, 'panel should retain a valid previous measurement')
assert.match(source, /contentHeight = 322/, 'unmeasured pages use independent minimum height, not previous page')
assert.match(source, /self:_requestPanelFit\(\)\s*tab\.Scroll\.Position/, 'primary switching must schedule fresh layout measurement')
console.log('Unified motion state machine, integration, teardown and package parity verified')
