import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
const read = path => readFileSync(new URL('../'+path,import.meta.url),'utf8')
const main=read('lib/RiftUI.luau')
const groups=read('lib/core/DockTabGroups.luau')
const bundle=read('public/RiftUI.luau')
const build=read('scripts/bundle.mjs')
const preview=read('examples/showcase.luau')
assert.ok(main.includes('--@@DOCK_TAB_GROUPS@@'), 'source marker missing')
assert.ok(build.includes('lib/core/DockTabGroups.luau'), 'group module absent in bundler')
assert.ok(bundle.includes(groups.trim()), 'compiled TabGroup module differs from source')
assert.ok(!bundle.includes('--@@DOCK_TAB_GROUPS@@'),'unexpanded tab-group marker')
assert.match(groups, /function Hub:TabGroup\(options\)/)
assert.match(groups, /function DockTabGroup:Tab\(options\)/)
assert.match(groups, /function DockTabGroup:SetOrder\(order\)/)
assert.match(groups, /self\.DockGroups\[name\] = group/, 'groups must be registered')
assert.match(groups, /list\(Enum\.FillDirection\.Horizontal/, 'each group must have own horizontal layout')
assert.match(groups, /AutomaticSize = Enum\.AutomaticSize\.X/, 'each group must auto size')
assert.match(main, /self\.DefaultTabGroup = self:TabGroup\(\{ Name = "Main"/, 'default group missing')
assert.match(main, /self\.SettingsGroup = self:TabGroup\(\{ Name = "Settings"/, 'settings group missing')
assert.match(main, /Group = "Settings" \}\)/, 'built-in Settings tab must belong to settings group')
assert.match(main, /Name = "OpenCommands"[^\n]*?LayoutOrder = 2000, Parent = self\.SettingsGroup\.Frame/, 'search must be right of settings in group')
assert.match(main, /Parent = group\.Frame/, 'first-level tabs should use group parent')
assert.match(main, /table\.insert\(group\.Tabs, tab\)/, 'group must register its tabs')
assert.match(main, /recordOptions\.Group = group\.Name/, 'reinitialize recipe must reference serializable group name')
assert.ok(!main.includes('LayoutOrder = -100, Parent = self.Dock'), 'search must not be left-most')
assert.match(groups, /DockGroupSeparator_/, 'settings divider must be owned by group')
assert.match(main, /self:_connect\(self\.CommandButton\.MouseButton1Click, function\(\) self:OpenCommandPalette\(\) end\)/, 'search handler must survive')
assert.match(preview, /Rift:CreateAuth\(/, 'DEMO preview gate must survive')
console.log('Dock grouping API, right-side Settings→Search order, legacy behavior and distribution verified')
