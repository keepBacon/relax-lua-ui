import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
const read = p => readFileSync(new URL('../' + p, import.meta.url), 'utf8')
const src = read('lib/RiftUI.luau')
const skins = read('lib/core/ControlThemes.luau')
const build = read('public/RiftUI.luau')
const bundler = read('scripts/bundle.mjs')
const zh = read('lib/core/Locales/zh.luau')
const preview = read('examples/showcase.luau')

assert.match(src, /--@@CONTROL_THEMES@@/, 'core marker missing')
assert.ok(bundler.includes('lib/core/ControlThemes.luau'), 'bundler missing control skins')
assert.ok(!build.includes('--@@CONTROL_THEMES@@'), 'unexpanded module marker')
assert.ok(build.includes(skins.trim()), 'compiled skins not synchronized')
assert.ok(skins.includes('function Hub:GetControlTheme()'))
assert.ok(skins.includes('function Hub:SetControlTheme(value)'))
assert.ok(skins.includes('function Hub:GetColorTheme()'))
assert.ok(skins.includes('function Hub:SetColorTheme(name)'))
assert.match(skins, /"Default", "Rounded"/)
for (const kind of ['Toggle','Slider','RangeSlider','Button','Dropdown','PlayerPicker','Keybind','Segmented','Input','ColorPicker','Stepper','Progress']) {
  assert.ok(skins.includes('kind == "' + kind + '"'), 'control skin missing: ' + kind)
}
assert.match(skins, /RoundedThumb/, 'rounded toggle needs an independent sliding thumb')
assert.match(skins, /RoundedValueBubble/, 'rounded slider needs a number preview bubble')
assert.match(skins, /RoundedSurfaceHighlight/, 'rounded button needs surface depth')
assert.match(skins, /RoundedFocusIndicator/, 'rounded input needs focused state')
assert.match(src, /self\.Hub:_attachControlTheme\(control\)/, 'control registration missing')
assert.match(src, /Name = "Color theme"/, 'color theme selector missing')
assert.match(src, /Name = "Control theme"/, 'control theme selector missing')
assert.ok(!src.includes('Name = "Theme",\n\t\t\tOptions = themeNames'), 'old selector must be removed')
assert.match(src, /saved\.ControlTheme/, 'startup must read saved control theme')
assert.match(src, /ControlTheme = self:GetControlTheme\(\)/, 'configs must include control theme')
assert.match(src, /self:SetControlTheme\(data\.ControlTheme\)/, 'config load must restore control theme')
assert.match(zh, /\["Color theme"\] = "颜色主题"/)
assert.match(zh, /\["Control theme"\] = "控件主题"/)
assert.match(zh, /\["Rounded"\] = "圆润"/)
assert.match(preview, /Name = "Control theme"/)
assert.match(preview, /Hub:SetControlTheme\(name\)/)
assert.match(preview, /Rift:CreateAuth\(/, 'DEMO preview key gate must remain')
console.log('Color theme / Default+Rounded control themes, visuals, lifecycle and configuration verified')
