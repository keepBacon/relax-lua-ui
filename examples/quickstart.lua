-- VortexionUI 1.0.0-final quickstart. Executor runtime required.
local UI=loadstring(game:HttpGet("https://raw.githubusercontent.com/keepBacon/relax-lua-ui/main/VortexionUI.lua"))()
local window=UI.CreateWindow({Title="VortexionLua",Subtitle="Quickstart",Width=760,Height=450,Transparency=0.24,BlurEnabled=false})
local group=window:CreateTabGroup("OVERVIEW")
local home=group:CreateTab("Home",{Selected=true})
local hero=home:CreateHero({Eyebrow="VORTEXION LUA",Title="Workspace ready",Description="Native, touch-friendly interface.",ActionText="Test callback",ActionIcon="check",Callback=function()window:Notify({Title="Quickstart",Content="Hero callback works."})end})
assert(hero.Button.Size.Y.Scale==0 and hero.Button.Size.Y.Offset<=40,"Hero button height regression")
home:CreateStatGrid({Columns=3,Items={{Title="Components",Value="Ready",Icon="grid"},{Title="Motion",Value="On",Icon="activity"},{Title="Platform",Value="Client",Icon="monitor"}}})
local controls=window:CreateTabGroup("CONTROLS")
local settings=controls:CreateTab("Settings")
settings:CreateToggle({Title="Enabled",Default=true})
settings:CreateSlider({Title="Power",Min=0,Max=100,Step=5,Default=45})
settings:CreateDropdown({Title="Quality",Options={"Comfort","Balanced","Realistic"},Default="Balanced"})
settings:CreateTextArea({Title="Notes",Default="Test on Android",Height=110})
return window
